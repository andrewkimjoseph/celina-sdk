#!/usr/bin/env node
/**
 * Generates src/analytics/mcp-tool-events.ts from tests/catalog (read ops with mcp.tool).
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const domainsDir = join(root, "tests/catalog/domains");
const outPath = join(root, "src/analytics/mcp-tool-events.ts");

/** @type {Record<string, string>} */
const map = {};

for (const file of readdirSync(domainsDir).filter((f) => f.endsWith(".ts"))) {
  const content = readFileSync(join(domainsDir, file), "utf8");

  for (const match of content.matchAll(
    /carbonRead\(\s*\n?\s*"([^"]+)",\s*\n?\s*"([^"]+)"/g,
  )) {
    map[match[1]] = match[2];
  }

  for (const chunk of content.split(/id: "/).slice(1)) {
    const id = chunk.split('"')[0];
    if (!chunk.includes('layer: "read"')) continue;
    const mcpMatch = chunk.match(/mcp:\s*\{[\s\S]*?tool:\s*"([^"]+)"/);
    if (mcpMatch) {
      map[id] = mcpMatch[1];
    }
  }
}

const sorted = Object.keys(map).sort();
if (sorted.length === 0) {
  console.error("No read MCP tool mappings found in catalog.");
  process.exit(1);
}

const lines = sorted.map(
  (id) => `  "${id}": "${map[id]}",`,
);

const source = `/**
 * Generated by scripts/generate-mcp-analytics-map.mjs — do not edit by hand.
 * Maps SDK method keys (catalog OperationSpec.id) to MCP tool event names.
 */
export const MCP_TOOL_EVENT_BY_SDK_METHOD: Readonly<Record<string, string>> = {
${lines.join("\n")}
} as const;
`;

mkdirSync(join(root, "src/analytics"), { recursive: true });
writeFileSync(outPath, source);
console.log(`Wrote ${sorted.length} mappings to src/analytics/mcp-tool-events.ts`);
