#!/usr/bin/env node
/**
 * Generates src/analytics/mcp-tool-events.ts and wallet-extract.ts from tests/catalog.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const domainsDir = join(root, "tests/catalog/domains");
const eventsOutPath = join(root, "src/analytics/mcp-tool-events.ts");
const walletOutPath = join(root, "src/analytics/wallet-extract.ts");

const WALLET_ARG_KEYS = new Set([
  "address",
  "agentAddress",
  "agent_address",
  "wallet_address",
  "from",
  "owner",
  "accountAddress",
  "fromAddress",
]);

/** @type {Record<string, string>} */
const map = {};

/** @type {Record<string, { positional?: number; objectKeys?: string[] }>} */
const walletMap = {};

function mergeWalletRule(id, rule) {
  const prev = walletMap[id] ?? {};
  walletMap[id] = {
    positional: rule.positional ?? prev.positional,
    objectKeys: rule.objectKeys
      ? [...new Set([...(prev.objectKeys ?? []), ...rule.objectKeys])]
      : prev.objectKeys,
  };
  if (
    walletMap[id].positional === undefined &&
    (!walletMap[id].objectKeys || walletMap[id].objectKeys.length === 0)
  ) {
    delete walletMap[id];
  }
}

function parseWalletFromChunk(id, chunk) {
  const argsMatch = chunk.match(/arguments:\s*\([^)]*\)\s*=>\s*\(\{([\s\S]*?)\}\)/);
  if (argsMatch) {
    const body = argsMatch[1];
    const keys = [];
    for (const key of WALLET_ARG_KEYS) {
      const re = new RegExp(`${key}:\\s*[^,}\\n]+`, "g");
      if (re.test(body)) {
        keys.push(key);
      }
    }
    if (keys.length > 0) {
      mergeWalletRule(id, { objectKeys: keys });
    }
  }

  const invokeMatch = chunk.match(/invoke:\s*\([^)]*\)\s*=>\s*([\s\S]*?),\s*\n\s*mcp:/);
  const invokeBody = invokeMatch?.[1] ?? chunk.match(/invoke:\s*\([^)]*\)\s*=>\s*([\s\S]*?)\n/)?.[1];
  if (!invokeBody) return;

  if (/\(\s*fx\.wallet\s*\)/.test(invokeBody) || /\(\s*fx\.signerAddress/.test(invokeBody)) {
    mergeWalletRule(id, { positional: 0 });
  } else if (/,\s*fx\.wallet\s*[,)]/.test(invokeBody)) {
    mergeWalletRule(id, { positional: 1 });
  } else if (/,\s*fx\.signerAddress/.test(invokeBody)) {
    mergeWalletRule(id, { positional: 1 });
  }
}

for (const file of readdirSync(domainsDir).filter((f) => f.endsWith(".ts"))) {
  const content = readFileSync(join(domainsDir, file), "utf8");

  for (const match of content.matchAll(
    /carbonRead\(\s*\n?\s*"([^"]+)",\s*\n?\s*"([^"]+)"/g,
  )) {
    map[match[1]] = match[2];
  }

  for (const chunk of content.split(/id: "/).slice(1)) {
    const id = chunk.split('"')[0];
    if (!chunk.includes('layer: "read"')) continue;
    const mcpMatch = chunk.match(/mcp:\s*\{[\s\S]*?tool:\s*"([^"]+)"/);
    if (mcpMatch) {
      map[id] = mcpMatch[1];
      parseWalletFromChunk(id, chunk);
    }
  }

  for (const match of content.matchAll(
    /carbonRead\(\s*\n?\s*"([^"]+)",\s*\n?\s*"([^"]+)"[\s\S]*?\(\)\s*=>\s*\(\{([^}]+)\}/g,
  )) {
    const id = match[1];
    map[id] = match[2];
    const body = match[3];
    const keys = [];
    for (const key of WALLET_ARG_KEYS) {
      if (new RegExp(`${key}:`).test(body)) {
        keys.push(key);
      }
    }
    if (keys.length > 0) {
      mergeWalletRule(id, { objectKeys: keys });
    }
    if (/getStrategies\(/.test(match[0]) || /\.getStrategies\(/.test(match[0])) {
      mergeWalletRule(id, { positional: 0 });
    }
    if (/getActivity\(/.test(match[0])) {
      mergeWalletRule(id, { objectKeys: ["wallet_address"] });
    }
  }
}

const sorted = Object.keys(map).sort();
if (sorted.length === 0) {
  console.error("No read MCP tool mappings found in catalog.");
  process.exit(1);
}

const eventLines = sorted.map((id) => `  "${id}": "${map[id]}",`);

const eventsSource = `/**
 * Generated by scripts/generate-mcp-analytics-map.mjs — do not edit by hand.
 * Maps SDK method keys (catalog OperationSpec.id) to MCP tool event names.
 */
export const MCP_TOOL_EVENT_BY_SDK_METHOD: Readonly<Record<string, string>> = {
${eventLines.join("\n")}
} as const;
`;

const walletSorted = Object.keys(walletMap).sort();
const walletLines = walletSorted.map((id) => {
  const rule = walletMap[id];
  const parts = [];
  if (rule.positional !== undefined) {
    parts.push(`positional: ${rule.positional}`);
  }
  if (rule.objectKeys?.length) {
    parts.push(`objectKeys: ${JSON.stringify(rule.objectKeys)}`);
  }
  return `  "${id}": { ${parts.join(", ")} },`;
});

const walletSource = `/**
 * Generated by scripts/generate-mcp-analytics-map.mjs — do not edit by hand.
 * Catalog-derived rules for extracting wallet addresses from SDK read call args.
 */
export type WalletExtractRule = {
  positional?: number;
  objectKeys?: readonly string[];
};

export const WALLET_EXTRACT_BY_SDK_METHOD: Readonly<
  Record<string, WalletExtractRule>
> = {
${walletLines.join("\n")}
} as const;
`;

mkdirSync(join(root, "src/analytics"), { recursive: true });
writeFileSync(eventsOutPath, eventsSource);
writeFileSync(walletOutPath, walletSource);
console.log(`Wrote ${sorted.length} mappings to src/analytics/mcp-tool-events.ts`);
console.log(`Wrote ${walletSorted.length} wallet rules to src/analytics/wallet-extract.ts`);
