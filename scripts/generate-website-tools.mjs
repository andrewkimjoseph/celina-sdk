#!/usr/bin/env node
/**
 * Writes celina-website/src/data/tools.generated.ts from the SDK tool catalog.
 * Run from celina-sdk after `npm run build`.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  deriveToolAvailability,
  getHostedMcpToolCount,
  getWebsiteToolBaselines,
} from "../build/tools/website-sync.js";
import { getToolDefinition } from "../build/tools/catalog.js";

const outPath = join(
  import.meta.dirname,
  "../../celina-website/src/data/tools.generated.ts",
);

const baselines = getWebsiteToolBaselines().map((baseline) => {
  const definition = getToolDefinition(baseline.name);
  if (!definition) {
    throw new Error(`Missing tool definition for ${baseline.name}`);
  }
  return {
    ...baseline,
    availability: deriveToolAvailability(definition),
  };
});
const hostedCount = getHostedMcpToolCount();

const body = `// Auto-generated by celina-sdk/scripts/generate-website-tools.mjs — do not edit by hand.
import type { ToolDoc } from "./tools.types.js";

export const GENERATED_HOSTED_TOOL_COUNT = ${hostedCount};

export const GENERATED_TOOL_NAMES = ${JSON.stringify(baselines.map((b) => b.name))} as const;

export const GENERATED_TOOLS: Omit<ToolDoc, "returns">[] = ${JSON.stringify(
  baselines,
  null,
  2,
)};
`;

mkdirSync(join(outPath, ".."), { recursive: true });
writeFileSync(outPath, body, "utf8");
console.log(`Wrote ${baselines.length} tools to ${outPath} (hosted: ${hostedCount})`);
